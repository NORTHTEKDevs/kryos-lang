#[test]
fn full_header_mixed_items() {
    let src = r#"
#include <stdio.h>

// A comment
#define MAX_SIZE 1024

typedef unsigned long size_t;

struct point {
    int x;
    int y;
};

enum direction { NORTH = 0, SOUTH = 1, EAST = 2, WEST = 3 };

int puts(const char* s);
void* malloc(size_t size);
int printf(const char* fmt, ...);
"#;
    let out = generate_bindings(src).unwrap();

    // Functions
    assert!(out.contains("fn puts(s: *u8) -> i32"));
    assert!(out.contains("fn malloc(size: usize) -> *u8"));
    assert!(out.contains("fn printf(fmt: *u8) -> i32")); // variadic params dropped

    // Struct
    assert!(out.contains("@repr(C)"));
    assert!(out.contains("struct point {"));
    assert!(out.contains("x: i32"));
    assert!(out.contains("y: i32"));

    // Enum constants
    assert!(out.contains("let NORTH: i32 = 0"));
    assert!(out.contains("let SOUTH: i32 = 1"));
    assert!(out.contains("let EAST: i32 = 2"));
    assert!(out.contains("let WEST: i32 = 3"));

    // Define
    assert!(out.contains("let MAX_SIZE: i32 = 1024"));

    // Typedef
    assert!(out.contains("type size_t = u64"));
}

#[test]
fn ignore_comments_and_includes() {
    let src = r#"
// Single line comment
/* Block comment
   spanning multiple lines */
#include <stdlib.h>
#include "myheader.h"
#ifdef _WIN32
#endif
int foo(void);
"#;
    let out = generate_bindings(src).unwrap();
    assert!(out.contains("fn foo()"));
    // Should not contain any include or ifdef artifacts
    assert!(!out.contains("#include"));
    assert!(!out.contains("#ifdef"));
}

