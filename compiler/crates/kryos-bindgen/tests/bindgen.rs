#[test]
fn variadic_function_drops_ellipsis() {
    let src = "int sprintf(char* buf, const char* fmt, ...);";
    let items = parse_c_header(src).unwrap();
    assert_eq!(items.len(), 1);
    match &items[0] {
        CItem::Function {
            name,
            params,
            variadic,
            ..
        } => {
            assert_eq!(name, "sprintf");
            assert!(*variadic);
            // Only the named params, not `...`
            assert_eq!(params.len(), 2);
        }
        other => panic!("expected Function, got {other:?}"),
    }

    let out = generate_bindings(src).unwrap();
    // The generated output should contain only the non-variadic params
    assert!(out.contains("fn sprintf(buf: *u8, fmt: *u8) -> i32"));
    assert!(!out.contains("..."));
}

