//! Integration tests for kryos-bindgen.

use kryos_bindgen::c_parser::{parse_c_header, CItem, CType};
use kryos_bindgen::generate_bindings;

// ---------------------------------------------------------------------------
// C parser tests
// ---------------------------------------------------------------------------

#[test]
fn parse_function_puts() {
    let items = parse_c_header("int puts(const char* s);").unwrap();
    assert_eq!(items.len(), 1);
    match &items[0] {
        CItem::Function {
            name,
            params,
            ret_ty,
            variadic,
        } => {
            assert_eq!(name, "puts");
            assert_eq!(*ret_ty, CType::Int);
            assert!(!variadic);
            assert_eq!(params.len(), 1);
            assert_eq!(params[0].ty, CType::Pointer(Box::new(CType::Char)));
            assert_eq!(params[0].name, Some("s".to_string()));
        }
        other => panic!("expected Function, got {other:?}"),
    }
}

